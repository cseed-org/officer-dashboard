/**
 * Turns scripts/seed/data.ts into idempotent SQL for D1 (`wrangler d1 execute --file`).
 *
 * Re-running is safe: rows are inserted only when their id is missing, and journal entries go through the real
 * draft → lines → post path guarded by "only while still draft", so the integrity
 * triggers check the seed's balances and never fire on a second run.
 */
import { contributionObligations } from '../../src/core/contributions';
import { fiscalYearRange } from '../../src/core/fiscal';
import { purchaseTotalCents } from '../../src/core/money';
import * as d from './data';

type V = string | number | boolean | null | undefined;
const lit = (v: V): string => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error(`bad number ${v}`);
    return String(v);
  }
  return `'${v.replaceAll("'", "''")}'`;
};
/**
 * Insert unless a row with this id exists. Not INSERT OR IGNORE: the integrity triggers
 * (rightly) refuse any insert that collides with a posted entry, closed period or audit row.
 */
const insert = (table: string, row: Record<string, V>) =>
  `INSERT INTO ${table} (${Object.keys(row).join(', ')}) SELECT ${Object.values(row).map(lit).join(', ')} ` +
  `WHERE NOT EXISTS (SELECT 1 FROM ${table} WHERE id = ${lit(row.id)});`;

/** Fixed clock so the seed is deterministic: 2026-10-30T12:00:00Z. */
const NOW = Date.UTC(2026, 9, 30, 12);
const ms = (iso: string) => {
  const t = Date.parse(iso.length === 10 ? `${iso}T12:00:00-07:00` : iso);
  if (Number.isNaN(t)) throw new Error(`bad date ${iso}`);
  return t;
};

/** Small deterministic PRNG (mulberry32) for guest lists. */
function rng(seed: number) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const FIRST = ['alex', 'bailey', 'casey', 'devon', 'emery', 'finley', 'gray', 'harper', 'indy', 'jules', 'kai', 'logan', 'morgan', 'noor', 'oakley', 'parker', 'quinn', 'riley', 'sage', 'taylor'];
const LAST = ['kim', 'nguyen', 'patel', 'garcia', 'smith', 'okafor', 'muller', 'tanaka', 'silva', 'cohen', 'haddad', 'ivanov'];

export function buildSeedSql(): string {
  const out: string[] = ['-- Generated by scripts/seed.ts. Sample data only; the chart of accounts needs CPA review.'];

  for (const u of d.users) {
    out.push(insert('users', { id: u.id, discord_id: u.discordId, name: u.name, role: u.role, title: u.title, email: u.email, active: true, created_at: NOW, updated_at: NOW }));
  }

  for (const a of d.accounts) {
    out.push(insert('accounts', {
      id: d.acct(a.code), code: a.code, name: a.name, type: a.type, normal_balance: a.normal, restriction: a.restriction ?? null,
      form990_part: a.part, form990_line: a.line, form990_label: a.label, budgetable: a.budgetable ?? false, active: true,
      description: a.description ?? null, created_at: NOW,
    }));
  }

  for (const donor of d.donors) {
    out.push(insert('donors', { id: donor.id, name: donor.name, type: donor.type, email: donor.email, created_at: NOW }));
  }
  for (const f of d.funds) {
    out.push(insert('funds', {
      id: f.id, code: f.code, name: f.name, kind: f.kind, restriction: f.restriction, purpose: f.purpose, donor_id: f.donorId,
      start_date: f.start, end_date: f.end, amount_awarded_cents: f.awardedCents, active: true, created_at: NOW,
    }));
  }

  // Events, guests, reflections.
  d.events.forEach((e, ei) => {
    out.push(insert('events', { id: e.id, luma_id: e.lumaId, name: e.name, starts_at: e.startsAt, ends_at: e.endsAt, location: e.location, url: `https://lu.ma/${e.lumaId}`, host_user_id: e.host, created_at: NOW, updated_at: NOW }));
    const rand = rng(ei + 1);
    const start = ms(e.startsAt);
    const checkedIn = Math.round(e.registered * e.checkInPct);
    const reflected = Math.round(checkedIn * e.reflectionPct);
    for (let g = 0; g < e.registered; g++) {
      const first = FIRST[g % FIRST.length]!;
      const last = LAST[Math.floor(g / FIRST.length + ei) % LAST.length]!;
      const email = `${first}.${last}${g}@example.edu`;
      const registeredAt = start - Math.floor(rand() * 14 * 86_400_000) - 3_600_000;
      const isIn = g < checkedIn;
      out.push(insert('event_guests', {
        id: `${e.id}-g${g}`, event_id: e.id, email, name: `${first[0]!.toUpperCase()}${first.slice(1)} ${last[0]!.toUpperCase()}${last.slice(1)}`,
        luma_guest_id: `gst-${e.lumaId}-${g}`, approval_status: 'approved', registered_at: registeredAt,
        checked_in_at: isIn ? start + Math.floor(rand() * 45 * 60_000) : null, created_at: NOW,
      }));
      if (isIn && g < reflected) {
        out.push(insert('reflections', {
          id: `${e.id}-r${g}`, event_id: e.id, email, submitted_at: start + 86_400_000 + Math.floor(rand() * 3 * 86_400_000),
          rating: 3 + Math.floor(rand() * 3), created_at: NOW,
        }));
      }
    }
  });

  // Purchase requests, approvals, fulfilment job for the approved club purchase.
  for (const r of d.requests) {
    out.push(insert('purchase_requests', {
      id: r.id, number: r.number, requester_id: r.requester, type: r.type, title: r.title, vendor: r.vendor, item_url: r.itemUrl,
      quantity: r.quantity, unit_cost_cents: r.unitCostCents, tax_ship_cents: r.taxShipCents,
      total_cents: purchaseTotalCents(r), expense_account_id: d.acct(r.account), fund_id: r.fund, event_id: r.event,
      functional_class: r.functionalClass, justification: r.justification, status: r.status,
      submitted_at: r.submittedAt ? ms(r.submittedAt) : null, decided_at: r.decidedAt ? ms(r.decidedAt) : null,
      created_at: r.submittedAt ? ms(r.submittedAt) - 3_600_000 : NOW, updated_at: NOW,
    }));
    if (r.decision && r.decidedAt) {
      out.push(insert('approvals', { id: `${r.id}-decision`, request_id: r.id, director_id: 'user-director', decision: r.decision.decision, comment: r.decision.comment, created_at: ms(r.decidedAt) }));
    }
    if (r.type === 'club_purchase' && ['approved', 'fulfilling', 'fulfilled'].includes(r.status)) {
      out.push(insert('fulfillment_jobs', { id: `${r.id}-job`, request_id: r.id, status: r.status === 'fulfilled' ? 'done' : 'queued', attempts: r.status === 'fulfilled' ? 1 : 0, created_at: NOW, updated_at: NOW }));
    }
  }

  // Budget for the fiscal year.
  for (const b of d.budgets) {
    out.push(insert('budgets', { id: `budget-${d.FISCAL_YEAR}-${b.account}-${b.fund ?? 'all'}`, fiscal_year: d.FISCAL_YEAR, account_id: d.acct(b.account), fund_id: b.fund, amount_cents: b.amountCents, notes: b.notes, created_at: NOW, updated_at: NOW }));
  }

  // Journal: draft → lines (only while draft) → post (only while draft).
  for (const e of d.journal) {
    out.push(insert('journal_entries', { id: e.id, entry_date: e.date, memo: e.memo, status: 'draft', source: e.source, purchase_request_id: e.request ?? null, created_by: 'user-director', created_at: NOW }));
    e.lines.forEach((l, i) => {
      const row: Record<string, V> = {
        id: `${e.id}-${i + 1}`, entry_id: e.id, line_no: i + 1, account_id: d.acct(l.account), fund_id: l.fund,
        functional_class: l.fc ?? null, debit_cents: l.debit ?? 0, credit_cents: l.credit ?? 0, memo: null,
      };
      out.push(
        `INSERT INTO journal_lines (${Object.keys(row).join(', ')}) SELECT ${Object.values(row).map(lit).join(', ')} ` +
          `WHERE (SELECT status FROM journal_entries WHERE id = ${lit(e.id)}) = 'draft' ` +
          `AND NOT EXISTS (SELECT 1 FROM journal_lines WHERE id = ${lit(row.id as string)});`,
      );
    });
    out.push(`UPDATE journal_entries SET status = 'posted', posted_at = ${NOW}, posted_by = 'user-director' WHERE id = ${lit(e.id)} AND status = 'draft';`);
  }

  for (const c of d.contributions) {
    const ob = contributionObligations({ amountCents: c.amountCents, quidProQuoCents: c.qpq });
    out.push(insert('contributions', {
      id: c.id, donor_id: c.donor, fund_id: c.fund, received_date: c.date, kind: c.kind, amount_cents: c.amountCents,
      quid_pro_quo_cents: c.qpq, acknowledgment_required: ob.acknowledgmentRequired, journal_entry_id: c.entry, created_at: NOW,
    }));
  }

  // Monthly fiscal periods; July–September closed. Inserted after the journal so the
  // sample July–September entries could still post.
  const { start } = fiscalYearRange(d.FISCAL_YEAR);
  const [y0, m0] = start.split('-').map(Number) as [number, number];
  for (let i = 0; i < 12; i++) {
    const first = new Date(Date.UTC(y0, m0 - 1 + i, 1));
    const last = new Date(Date.UTC(y0, m0 + i, 0));
    const iso = (dt: Date) => dt.toISOString().slice(0, 10);
    const name = first.toLocaleString('en-US', { month: 'short', year: 'numeric', timeZone: 'UTC' });
    out.push(insert('fiscal_periods', {
      id: `period-${iso(first).slice(0, 7)}`, fiscal_year: d.FISCAL_YEAR, name, start_date: iso(first), end_date: iso(last),
      status: i < 3 ? 'closed' : 'open', closed_at: i < 3 ? NOW : null, closed_by: i < 3 ? 'user-director' : null, created_at: NOW,
    }));
  }

  return `${out.join('\n')}\n`;
}
